#!/usr/bin/env python3
"""CMSIS-RTOS2 personality trim: generate and verify a profile.

The manifest (``user/cmsis_rtos2/cmsis_rtos2.toml``) declares which object
families a profile keeps and which Native ABI syscalls those families need.
This tool turns one declaration into the two artefacts a build consumes and
verifies a built kernel against the same declaration:

    emit   -> cmsis_config.h + syscall_table_<profile>.def
    check  -> every sys_a20_* symbol in the kernel ELF is in the profile
    list   -> print a profile

Nothing is copied by hand, so the generated table and the verifier cannot
disagree about what "the MCU profile" means.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "user" / "cmsis_rtos2" / "cmsis_rtos2.toml"
MASTER_DEF = ROOT / "kernel" / "abi" / "native" / "syscall_table.def"

_DEF_RE = re.compile(r"^A20_NATIVE_SYSCALL\(\s*([a-z0-9_]+)\s*,\s*(.+?)\s*\)\s*$")


class TrimError(Exception):
    pass


def load_manifest(path: Path = MANIFEST) -> dict:
    with path.open("rb") as fh:
        return tomllib.load(fh)


def parse_master(path: Path = MASTER_DEF) -> dict[str, str]:
    """Return syscall name -> handler expression, in file order."""
    entries: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("/*") or line.startswith("*"):
            continue
        m = _DEF_RE.match(line)
        if m:
            entries[m.group(1)] = m.group(2)
    if not entries:
        raise TrimError(f"{path}: no A20_NATIVE_SYSCALL entries")
    return entries


def get_profile(manifest: dict, name: str) -> dict:
    profiles = manifest.get("profile")
    if not isinstance(profiles, dict) or name not in profiles:
        known = ", ".join(sorted(profiles or {}))
        raise TrimError(f"unknown profile {name!r}; known: {known}")
    return profiles[name]


def feature_macros(manifest: dict) -> dict[str, str]:
    table = manifest.get("feature_macro")
    if not isinstance(table, dict) or not table:
        raise TrimError("manifest has no [feature_macro] table")
    return table


def resolve_syscalls(manifest: dict, profile: dict, master: dict[str, str]
                     ) -> list[str]:
    declared = profile.get("syscalls", [])
    if declared == "all":
        return list(master)
    if not isinstance(declared, list):
        raise TrimError("profile syscalls must be a list or the string 'all'")
    reasons = manifest.get("syscall_reason", {})
    unknown = [n for n in declared if n not in master]
    if unknown:
        raise TrimError(f"unknown syscalls: {', '.join(unknown)}")
    missing_reason = [n for n in declared if n not in reasons]
    if missing_reason:
        raise TrimError(
            "syscalls without a [syscall_reason] entry: "
            + ", ".join(missing_reason))
    # Keep master order so table indexes are stable between profiles.
    wanted = set(declared)
    return [name for name in master if name in wanted]


def render_config(manifest: dict, profile_name: str, profile: dict) -> str:
    macros = feature_macros(manifest)
    enabled = set(profile.get("features", []))
    unknown = enabled - set(macros)
    if unknown:
        raise TrimError(f"unknown features: {', '.join(sorted(unknown))}")
    lines = [
        "/*",
        " * Generated by tools/cmsis_trim.py from",
        f" * user/cmsis_rtos2/cmsis_rtos2.toml, profile '{profile_name}'.",
        " * Do not edit: change the manifest and regenerate.",
        " */",
        "#ifndef CMSIS_RTOS2_CONFIG_H",
        "#define CMSIS_RTOS2_CONFIG_H",
        "",
    ]
    for feature, macro in macros.items():
        lines.append(f"#define {macro} {1 if feature in enabled else 0}")
    lines += ["", "#endif /* CMSIS_RTOS2_CONFIG_H */", ""]
    return "\n".join(lines)


def render_def(profile_name: str, syscalls: list[str],
               master: dict[str, str]) -> str:
    lines = [
        "/*",
        " * Generated by tools/cmsis_trim.py from",
        f" * kernel/abi/native/syscall_table.def, profile '{profile_name}'.",
        " * Do not edit: change the manifest and regenerate.",
        " *",
        " * Same X-macro contract as the master table: no include guard.",
        " */",
        '#include "abi/native/syscall_nr.h"',
        "",
        "#ifndef A20_NATIVE_SYSCALL",
        '#error "A20_NATIVE_SYSCALL must be defined before including this file"',
        "#endif",
        "",
    ]
    for name in syscalls:
        lines.append(f"A20_NATIVE_SYSCALL({name}, {master[name]})")
    lines.append("")
    return "\n".join(lines)


def emit(profile_name: str, out_dir: Path, manifest: dict | None = None,
         master: dict[str, str] | None = None) -> dict[str, Path]:
    manifest = manifest or load_manifest()
    master = master or parse_master()
    profile = get_profile(manifest, profile_name)
    syscalls = resolve_syscalls(manifest, profile, master)

    out_dir.mkdir(parents=True, exist_ok=True)
    config = out_dir / "cmsis_config.h"
    table = out_dir / f"syscall_table_{profile_name}.def"
    config.write_text(render_config(manifest, profile_name, profile),
                      encoding="utf-8")
    table.write_text(render_def(profile_name, syscalls, master),
                     encoding="utf-8")
    return {"config": config, "table": table, "syscalls": syscalls}


def _nm_binary() -> str:
    for candidate in (os.environ.get("A20_NM"), "llvm-nm", "nm"):
        if candidate and (Path(candidate).exists() or
                          subprocess.run(["/bin/sh", "-c", f"command -v {candidate}"],
                                         capture_output=True).returncode == 0):
            return candidate
    raise TrimError("no nm found; set A20_NM")


def read_defined_syscalls(elf: Path, nm: str | None = None) -> set[str]:
    if not elf.exists():
        raise TrimError(f"{elf}: no such file")
    nm = nm or _nm_binary()
    proc = subprocess.run([nm, str(elf)], capture_output=True, text=True)
    if proc.returncode != 0:
        raise TrimError(f"{nm} {elf} failed: {proc.stderr.strip()}")
    defined: set[str] = set()
    for line in proc.stdout.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        kind, name = parts[-2], parts[-1]
        if kind in {"U", "u"}:
            continue
        if name.startswith("sys_a20_"):
            defined.add(name[len("sys_a20_"):])
    return defined


def check(profile_name: str, elf: Path, nm: str | None = None,
          manifest: dict | None = None,
          master: dict[str, str] | None = None) -> dict:
    manifest = manifest or load_manifest()
    master = master or parse_master()
    profile = get_profile(manifest, profile_name)
    allowed = set(resolve_syscalls(manifest, profile, master))
    present = read_defined_syscalls(elf, nm)

    extra = sorted(present - allowed)
    missing = sorted(allowed - present)
    if extra:
        raise TrimError(
            "kernel links syscalls outside profile "
            f"'{profile_name}': {', '.join(extra)}")
    if missing:
        raise TrimError(
            "kernel is missing profile syscalls "
            f"'{profile_name}': {', '.join(missing)}")
    return {"profile": profile_name, "syscalls": sorted(present),
            "count": len(present)}


def describe(profile_name: str, manifest: dict | None = None,
             master: dict[str, str] | None = None) -> str:
    manifest = manifest or load_manifest()
    master = master or parse_master()
    profile = get_profile(manifest, profile_name)
    syscalls = resolve_syscalls(manifest, profile, master)
    features = ", ".join(profile.get("features", [])) or "(none)"
    reasons = manifest.get("syscall_reason", {})
    lines = [f"profile {profile_name}",
             f"  features: {features}",
             f"  syscalls: {len(syscalls)}"]
    for name in syscalls:
        lines.append(f"    {name:16s} {reasons.get(name, '')}")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_list = sub.add_parser("list", help="print a profile")
    p_list.add_argument("--profile", default="mcu")

    p_emit = sub.add_parser("emit", help="generate config and syscall table")
    p_emit.add_argument("--profile", required=True)
    p_emit.add_argument("--out", required=True, type=Path)

    p_check = sub.add_parser("check", help="verify a kernel ELF")
    p_check.add_argument("--profile", required=True)
    p_check.add_argument("--elf", required=True, type=Path)
    p_check.add_argument("--nm", default=None)

    args = ap.parse_args(argv)
    try:
        if args.cmd == "list":
            print(describe(args.profile))
        elif args.cmd == "emit":
            out = emit(args.profile, args.out)
            print(f"cmsis-trim[{args.profile}]: {out['config']}")
            print(f"cmsis-trim[{args.profile}]: {out['table']} "
                  f"({len(out['syscalls'])} syscalls)")
        elif args.cmd == "check":
            result = check(args.profile, args.elf, args.nm)
            print(f"cmsis-trim[{args.profile}]: {result['count']} syscalls OK")
    except TrimError as exc:
        print(f"cmsis-trim: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
