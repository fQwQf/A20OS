#!/usr/bin/env python3
"""Resolve virtio-console memory presets and emit a change-detected build header."""
from __future__ import annotations

import argparse
import os
import tempfile
from pathlib import Path

PRESETS = {
    'throughput': dict(rx_slots=8, tx_slots=16, buffer_size=4096, ring_size=4096),
    'compact': dict(rx_slots=2, tx_slots=2, buffer_size=512, ring_size=512),
}
MACROS = {
    'rx_slots': 'CONFIG_VIRTIO_CONSOLE_RX_SLOTS',
    'tx_slots': 'CONFIG_VIRTIO_CONSOLE_TX_SLOTS',
    'buffer_size': 'CONFIG_VIRTIO_CONSOLE_BUFFER_SIZE',
    'ring_size': 'CONFIG_VIRTIO_CONSOLE_RING_SIZE',
}
LIMITS = {'rx_slots': (1, 16), 'tx_slots': (1, 16),
          'buffer_size': (64, 4096), 'ring_size': (128, 65536)}


def resolve(profile=None, **overrides):
    profile = 'throughput' if profile is None else profile
    if profile not in PRESETS:
        raise ValueError('virtio_console_profile must be throughput or compact')
    values = dict(PRESETS[profile])
    for name, value in overrides.items():
        if name not in MACROS:
            raise ValueError(f'unknown virtio-console parameter: {name}')
        if value is not None:
            values[name] = value
    for name, value in values.items():
        low, high = LIMITS[name]
        if (not isinstance(value, int) or isinstance(value, bool) or
                not low <= value <= high or value & (value - 1)):
            raise ValueError(f'virtio_console_{name} must be a power of two in [{low}, {high}]')
    return values


def header(values):
    return ('/* Generated by tools/virtio_console_config.py. */\n' +
            ''.join(f'#define {macro} {values[name]}\n' for name, macro in MACROS.items()))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', default='throughput')
    for name in MACROS:
        parser.add_argument('--' + name.replace('_', '-'), type=int)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    try:
        values = resolve(args.profile, **{name: getattr(args, name) for name in MACROS})
    except ValueError as exc:
        parser.error(str(exc))
    text = header(values)
    # Do not invalidate the module when make rechecks an unchanged preset.
    if not args.output.exists() or args.output.read_text() != text:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(mode='w', dir=args.output.parent, delete=False) as stream:
            name = stream.name
            stream.write(text)
        try:
            os.replace(name, args.output)
        finally:
            if os.path.exists(name):
                os.unlink(name)


if __name__ == '__main__':
    main()
