#include <assert.h>
#include <stdio.h>
#include <string.h>
#include "uapi/a20/cluster_membership.h"

static a20_member_t nodes[3];
static a20_member_service_t services[4];
static a20_membership_t membership;
static void alive(unsigned i, uint64_t epoch, uint64_t now) {
    uint64_t cookie = a20_member_probe(&membership, i, now);
    assert(cookie && a20_member_observe(&membership, i, cookie, epoch, 0, 2,
                                        i ? 2 : 1, now + 1, 1) == 0);
}
static a20_member_service_t work(unsigned max_input, unsigned process) {
    a20_member_service_t s = {.slot = 2,
                              .name_len = 4,
                              .kinds = A20_WORK_CAP_OPERATOR |
                                       (process ? A20_WORK_CAP_PROCESS : 0),
                              .max_inflight = 1,
                              .max_input = max_input,
                              .max_output = 8,
                              .operator_count = 1};
    memcpy(s.name, "work", 4);
    s.operators[0] = (a20_member_operator_t){A20_WORK_DOT, A20_WORK_REPLAY_SAFE,
                                             max_input, 8};
    return s;
}
static int select_work(unsigned kind, unsigned bytes, uint64_t now) {
    return a20_member_select(&membership, "work", 4, kind, 1, bytes, now);
}
int main(void) {
    assert(a20_membership_init(&membership, nodes, 3, services, 4, 100, 300,
                               1000) == 0);
    uint8_t id[16] = {0};
    for (unsigned i = 0; i < 3; i++) {
        id[15] = i + 1;
        assert(a20_member_add(&membership, id) == (int)i);
    }
    id[15] = 4;
    assert(a20_member_add(&membership, id) == -1);
    assert(select_work(A20_WORK_OPERATOR, 12, 0) == -1);
    alive(0, 100, 0);
    alive(1, 200, 0);
    alive(2, 300, 0);
    a20_member_service_t mcu = work(140, 0), host = work(1024, 1);
    assert(a20_member_publish(&membership, 0, &mcu, 1, 1, 1000, 2) == 0);
    assert(a20_member_publish(&membership, 1, &host, 1, 1, 1000, 2) == 0);
    assert(select_work(A20_WORK_OPERATOR, 12, 3) == 0);
    assert(select_work(A20_WORK_OPERATOR, 12, 3) == 1);
    assert(select_work(A20_WORK_OPERATOR, 141, 3) == 1);
    assert(select_work(A20_WORK_PROCESS, 0, 3) == 1);
    assert(select_work(A20_WORK_PROCESS, 1, 3) == -1);
    a20_member_service_t invalid[2] = {mcu, mcu};
    assert(a20_member_publish(&membership, 0, invalid, 2, 2, 1000, 4) == -1);
    assert(services[0].generation ==
           1); /* Failed publish kept the old snapshot. */
    uint64_t cookie = a20_member_probe(&membership, 1, 10);
    assert(a20_member_observe(&membership, 1, cookie - 1, 200, 0, 2, 2, 11, 1) <
           0);
    assert(a20_member_observe(&membership, 1, cookie, 201, 0, 2, 2, 11, 0) < 0);
    a20_membership_tick(&membership, 110);
    assert(nodes[1].state == A20_MEMBER_SUSPECT);
    assert(select_work(A20_WORK_PROCESS, 0, 111) == -1);
    cookie = a20_member_probe(&membership, 1, 111);
    assert(a20_member_observe(&membership, 1, cookie, 200, 0, 2, 2, 112, 0) ==
           0);
    assert(select_work(A20_WORK_PROCESS, 0, 113) == 1);
    assert(a20_member_suspect(&membership, 1, 200, 4, 120) == 0);
    assert(a20_member_suspect(&membership, 1, 199, 5, 121) < 0);
    assert(a20_member_suspect(&membership, 1, 200, 4, 400) == 0);
    assert(nodes[1].state_deadline ==
           420); /* Rumors cannot extend suspicion forever. */
    a20_membership_tick(&membership, 420);
    assert(nodes[1].state == A20_MEMBER_DEAD && !services[1].used);
    assert(a20_member_suspect(&membership, 1, 200, 5, 421) < 0);
    cookie = a20_member_probe(&membership, 1, 421);
    assert(a20_member_observe(&membership, 1, cookie, 201, 0, 2, 2, 422, 1) ==
           0);
    assert(select_work(A20_WORK_PROCESS, 0, 423) ==
           -1); /* Epoch change invalidates capabilities. */
    assert(a20_member_publish(&membership, 1, &host, 1, 2, 20, 423) == 0);
    assert(select_work(A20_WORK_PROCESS, 0, 424) >= 0);
    a20_membership_tick(&membership, 443);
    assert(select_work(A20_WORK_PROCESS, 0, 443) == -1); /* Lease expiry. */
    assert(a20_member_suspect(&membership, 2, 300, 0, 450) == 0);
    a20_membership_tick(&membership, 750);
    a20_membership_tick(&membership, 1750);
    assert(nodes[2].state == A20_MEMBER_EMPTY);
    assert(a20_member_add(&membership, id) == 2);
    uint64_t incarnation = 4;
    assert(a20_member_refute(9, &incarnation) == 0 && incarnation == 10);
    assert(a20_member_refute(UINT64_MAX, &incarnation) == -1);
    /* Decode capabilities generated by the actual shared agent. */
    const a20_work_operator_t ops[] = {
        {1, A20_WORK_REPLAY_SAFE, 140, 8, a20_work_dot, 0}};
    const a20_work_agent_t agent = {.operators = ops,
                                    .operator_count = 1,
                                    .max_input = 140,
                                    .max_output = 8,
                                    .max_inflight = 1,
                                    .max_budget_ms = 30000};
    uint8_t request[32], reply[128];
    a20_work_request_t query = {.kind = A20_WORK_QUERY};
    int n = a20_work_encode(request, sizeof(request), &query);
    n = a20_work_dispatch(&agent, request, n, reply, sizeof(reply));
    a20_work_result_t result;
    assert(a20_work_result_decode(reply, n, &query, &result) == 0);
    assert(a20_member_capabilities(&mcu, &result) == 0 && mcu.max_input == 140);
    a20_work_put32(reply + 52, UINT32_MAX);
    assert(a20_member_capabilities(&mcu, &result) < 0);
    puts("test_clx_membership: mixed capabilities, atomic publication, leases, "
         "suspicion, indirect probes, reboot and tombstones passed");
}
