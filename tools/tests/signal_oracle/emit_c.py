#!/usr/bin/env python3
"""Emit C run-functions for the vector subset implemented by model_c.c."""
import sys
import vectors

OPS = []


def bits(seq):
    m = 0
    for s in seq:
        m |= 1 << s
    return m


def emit(vec):
    lines = []
    lines.append("static void run_%s(void) {" % vec['id'])
    for op in vec['ops']:
        name = op[0]
        if name == 'action':
            _, sig, kind, flags, mask = op
            lines.append("  op_action(%d, %d, 0x%xU, 0x%xULL);" % (sig, kind, flags, bits(mask)))
        elif name == 'queue':
            _, scope, sig, info = op
            info_c = 'NULL' if info is None else '"%s"' % info
            lines.append("  op_queue(%d, %d, %s);" % (0 if scope == 'proc' else 1, sig, info_c))
        elif name == 'deliver':
            lines.append("  op_deliver();")
        elif name == 'kdeliver':
            lines.append("  op_kdeliver();")
        elif name == 'boundary':
            lines.append("  op_boundary();")
        elif name == 'sigreturn':
            lines.append("  op_sigreturn();")
        elif name == 'timedwait':
            _, mask, poll = op
            lines.append("  op_timedwait(0x%xULL, %d);" % (bits(mask), poll))
        elif name == 'maskop':
            _, how, sset = op
            if sset is None:
                lines.append("  op_maskop_none(%d);" % how)
            else:
                lines.append("  op_maskop(%d, 0x%xULL);" % (how, bits(sset)))
        elif name == 'sigsuspend':
            lines.append("  op_sigsuspend(0x%xULL);" % bits(op[1]))
        elif name == 'wake':
            lines.append("  op_wake();")
        elif name == 'restore':
            lines.append("  op_restore();")
        elif name == 'exec':
            lines.append("  op_exec();")
        elif name == 'actions':
            sigs = list(op[1]) + [0]
            arg = ", ".join(str(s) for s in sigs)
            lines.append("  op_actions(%s);" % arg)
        elif name == 'tmpmask':
            lines.append("  op_tmpmask(0x%xULL);" % bits(op[1]))
        elif name == 'tmpres':
            lines.append("  op_tmpres();")
        elif name == 'sfdcreate':
            lines.append("  op_sfdcreate(0x%xULL);" % bits(op[1]))
        elif name == 'sfdmask':
            lines.append("  op_sfdmask(0x%xULL);" % bits(op[1]))
        elif name == 'sfdread':
            lines.append("  op_sfdread(%d, %d);" % (op[1], op[2]))
        elif name == 'sfdpoll':
            lines.append("  op_sfdpoll();")
        elif name == 'restart':
            lines.append("  op_restart();")
        elif name == 'np':
            lines.append("  op_np(%d, %d);" % (0 if op[1] == 'proc' else 1, op[2]))
        elif name == 'ncheck':
            lines.append("  op_ncheck(%d, 0x%xULL);" % (op[1], bits(op[2])))
        elif name == 'nmask':
            lines.append("  op_nmask(0x%xULL);" % bits(op[1]))
        elif name == 'nblock':
            lines.append("  op_nblock(0x%xULL);" % bits(op[1]))
        elif name == 'ntake':
            lines.append("  op_ntake();")
        elif name == 'nstate':
            lines.append("  op_nstate();")
        else:
            raise SystemExit("emit_c: no C op for %r in %s" % (op, vec['id']))
    lines.append("}")
    return "\n".join(lines)


def main():
    out = open(sys.argv[1], 'w')
    out.write("/* generated by emit_c.py from vectors.py; do not edit */\n")
    cm = [v for v in vectors.VECTORS if v['cmodel']]
    for vec in cm:
        out.write(emit(vec))
        out.write("\n")
    out.write("static const struct { const char *id; void (*run)(void); } g_vectors[] = {\n")
    for vec in cm:
        out.write('  {"%s", run_%s},\n' % (vec['id'], vec['id']))
    out.write("  {NULL, NULL}\n};\n")
    out.close()
    print("emitted %d C vectors" % len(cm))


if __name__ == '__main__':
    main()
